#!/usr/bin/env python3
"""将已生成的课件打包到 _site，供 GitHub Pages 直接发布。"""

import hashlib
import json
from pathlib import Path
import re
import shutil


ROOT = Path(__file__).resolve().parents[1]
COURSE = ROOT / "第01讲-LLM-Agents" / "v02-导入与LLM基础HTML"
OUTPUT = ROOT / "_site"
MARKER = ".mba-pages-build"


def main():
    manifest = json.loads((COURSE / "version_manifest.json").read_text())
    slides = json.loads((COURSE / "slides.json").read_text())
    if len(slides) != manifest["page_count"]:
        raise ValueError("课件页数与版本清单不一致，请先运行 qa/build-data.cjs")

    html = (COURSE / "index.html").read_text()
    refs = re.findall(r'(?:src|href)="([^"?]+\.(?:js|css))\?v=([^"&]+)"', html)
    if not refs:
        raise ValueError("未找到带版本校验值的播放资源")
    for name, expected in refs:
        actual = hashlib.sha256((COURSE / name).read_bytes()).hexdigest()[:12]
        if expected != actual:
            raise ValueError(f"资源版本不一致：{name}，请先运行 qa/build-data.cjs")

    if OUTPUT.exists():
        if OUTPUT.is_symlink() or not (OUTPUT / MARKER).is_file():
            raise ValueError("_site 已存在且不是本脚本的产物，请另行保存后重试")
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    (OUTPUT / MARKER).write_text("Generated by scripts/build-pages.py\n")

    for name in ["index.html", "slides.json", "materials.json", "schedule.json", "version_manifest.json"]:
        shutil.copy2(COURSE / name, OUTPUT / name)
    for name in ["src", "assets", "sources"]:
        shutil.copytree(
            COURSE / name,
            OUTPUT / name,
            ignore=shutil.ignore_patterns(".DS_Store", "__pycache__", "*.pyc"),
        )
    (OUTPUT / ".nojekyll").touch()

    # 项目站点继承 CHIANGEL.github.io 的域名，不在此写入 CNAME。
    files = [p for p in OUTPUT.rglob("*") if p.is_file()]
    print(json.dumps({
        "revision": manifest["revision"],
        "pages": len(slides),
        "files": len(files),
        "size_mib": round(sum(p.stat().st_size for p in files) / 1048576, 2),
        "output": str(OUTPUT),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
